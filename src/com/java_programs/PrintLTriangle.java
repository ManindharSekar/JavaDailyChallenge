package com.java_programs;

public class PrintLTriangle {

	// Program: Print L Triangle Pattern
	// Day: 28
	// Added on: 05-Dec-2025

	public static void main(String[] args) {

		for (int i = 0; i <= 4; i++) {
			for (int j = 0; j <= i; j++) {
				System.out.print("*");
			}
			System.out.println();
		}

	}

}
